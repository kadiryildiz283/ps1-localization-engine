def apply_translations():
    path = 'translations/ui_english.json'
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    for item in data:
        iid = item['id']
        if iid in UI_TRANSLATIONS:
            item['translation'] = UI_TRANSLATIONS[iid]
        elif 'translation' not in item or not item['translation']:
            item['translation'] = item['text']

    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f'Successfully applied translations to all {len(data)} UI items in {path}')

if __name__ == '__main__':
    apply_translations()
