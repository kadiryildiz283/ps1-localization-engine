#!/usr/bin/env python3
"""İki Türkçe bayrak dokusu (128x64, 16-bit PS1 RGB555) → C header.

Bayrak ekranına eklenecek iki seçenek:
  bank 1: TR + ALTYAZI        (TR metin + orijinal EN ses)
  bank 2: TR + DUBLAJ+ALTYAZI (TR metin + TR ses)

Kullanım: python3 tools/gen_tr_flag_tex.py > src/tr_flag_tex.h
"""
from PIL import Image, ImageDraw

W, H = 128, 64
RED = (227, 10, 23)
WHITE = (255, 255, 255)


def rgb555(r, g, b):
    # bit15 (STP/mask) = 0: opak, mask-check discard yok
    return (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)


def flag_base():
    img = Image.new("RGB", (W, H), RED)
    d = ImageDraw.Draw(img)
    # hilal: dış beyaz daire - iç kırmızı daire
    d.ellipse([28, 12, 68, 52], fill=WHITE)
    d.ellipse([36, 16, 72, 48], fill=RED)
    # yıldız (beş köşe)
    import math
    cx, cy, r = 78, 32, 11
    pts = []
    for i in range(10):
        ang = -math.pi / 2 + i * math.pi / 5
        rr = r if i % 2 == 0 else r * 0.45
        pts.append((cx + rr * math.cos(ang), cy + rr * math.sin(ang)))
    d.polygon(pts, fill=WHITE)
    return img


def with_label(img, text):
    d = ImageDraw.Draw(img)
    d.rectangle([0, H - 14, W, H], fill=(0, 0, 0))
    d.text((4, H - 13), text, fill=WHITE)
    return img


def emit(name, img):
    px = img.load()
    vals = [rgb555(*px[x, y]) for y in range(H) for x in range(W)]
    print(f"static const uint16_t {name}[{W * H}] = {{")
    for i in range(0, len(vals), 12):
        print("  " + ",".join(str(v) for v in vals[i:i + 12]) + ",")
    print("};")


a = with_label(flag_base(), "TR ALTYAZI")
b = with_label(flag_base(), "TR DUBLAJ+ALTYAZI")
print("/* auto-generated by tools/gen_tr_flag_tex.py — do not edit */")
print("#pragma once")
print("#include <stdint.h>")
print(f"#define TR_FLAG_W {W}")
print(f"#define TR_FLAG_H {H}")
emit("tr_flag_sub", a)
emit("tr_flag_dub", b)
